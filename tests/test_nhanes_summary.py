"""Focused tests using fictional summaries; no study data are bundled here.

Run: python -m unittest discover -s tests -p test_nhanes_summary.py
"""

import copy
import importlib.util
import json
import math
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

import numpy as np
from scipy.stats import t


MODULE_PATH = Path(__file__).resolve().parents[1] / "tools" / "verify_nhanes_summary.py"
SPEC = importlib.util.spec_from_file_location("summary_verifier_under_test", MODULE_PATH)
VERIFIER = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(VERIFIER)


def fictional_summary():
    """Independent diagonal covariance with manually specified contrasts.

    Fieller endpoints were calculated with 60-digit decimal arithmetic from
    H=.05, G=.10, var(H)=.000034, var(G)=.000041, cov(H,G)=.000025.
    They are fixed references, not generated by the implementation under test.
    """
    q = float(t.ppf(0.975, 20))

    def record(value, variance):
        se = math.sqrt(variance)
        return {"estimate": value, "SE": se, "lower": value - q * se,
                "upper": value + q * se, "confidence_level": 0.95, "df": 20}

    domain = {
        "n": 100, "events_5y": 10, "weighted_event_fraction": 0.1, "df": 20,
        "route_order": ["B", "M", "S", "MEAN", "P"],
        "Brier": {
            "B": record(0.30, 0.000025), "M": record(0.20, 0.000016),
            "S": record(0.25, 0.000009), "MEAN": record(0.28, 0.000004),
            "P": record(0.26, 0.000001),
        },
        "contrasts": {
            "G_measured_gain": record(0.10, 0.000041),
            "D_substitution_loss": record(0.05, 0.000025),
            "H_remaining_gain": record(0.05, 0.000034),
            "A_proxy_over_mean": record(0.03, 0.000013),
            "G_P_retrained_proxy_gain": record(0.04, 0.000026),
        },
        "joint_covariance_of_route_losses": np.diag(
            [0.000025, 0.000016, 0.000009, 0.000004, 0.000001]).tolist(),
        "retention": {
            "point": 0.5, "guard": 1e-8, "confidence_level": 0.95,
            "set_type": "bounded", "intervals": [[0.40563612002459837, 0.590376627852329]],
            "denominator_supported_positive": True, "headline_percentage_allowed": True,
        },
        "unweighted_sensitivity": {
            "route_Brier": {"B": 0.31, "M": 0.22, "S": 0.27, "MEAN": 0.29, "P": 0.30},
            "contrasts": {"G_measured_gain": 0.09, "D_substitution_loss": 0.05,
                          "H_remaining_gain": 0.04, "A_proxy_over_mean": 0.02,
                          "G_P_retrained_proxy_gain": 0.01},
        },
    }
    return {"primary_40plus": domain, "sensitivity_40_79": copy.deepcopy(domain)}


class FiellerTests(unittest.TestCase):
    def assert_set(self, arguments, kind, intervals):
        result = VERIFIER.fieller_set(*arguments)
        self.assertEqual(result["set_type"], kind)
        self.assertEqual(len(result["intervals"]), len(intervals))
        np.testing.assert_allclose(result["intervals"], intervals, atol=1e-12, rtol=1e-12)

    def test_known_bounded_and_singleton(self):
        # (1 - 2r)^2 <= 1; with zero variance it reduces to r = 1/2.
        self.assert_set((1, 2, 0.25, 0, 0, 2), "bounded", [[0, 1]])
        self.assert_set((1, 2, 0, 0, 0, 1), "bounded", [[0.5, 0.5]])

    def test_disjoint_and_all_real_sets(self):
        # 3 - r^2 <= 0 and -1 - r^2 <= 0, respectively.
        self.assert_set((2, 0, 1, 1, 0, 1), "disjoint",
                        [[-math.inf, -math.sqrt(3)], [math.sqrt(3), math.inf]])
        self.assert_set((0, 0, 1, 1, 0, 1), "all_real", [[-math.inf, math.inf]])
        self.assert_set((1, 0, 1, 1, 0, 1), "all_real", [[-math.inf, math.inf]])

    def test_both_linear_half_lines(self):
        self.assert_set((1, 1, 1, 1, 0, 1), "half_line", [[0, math.inf]])
        self.assert_set((-1, 1, 1, 1, 0, 1), "half_line", [[-math.inf, 0]])

    def test_constant_empty_and_all_real(self):
        self.assert_set((1, 0, 0, 0, 0, 1), "empty", [])
        self.assert_set((0, 0, 0, 0, 0, 1), "all_real", [[-math.inf, math.inf]])

    def test_scale_invariance_including_small_units(self):
        # A unit conversion must not turn a tiny covariance into a zero matrix.
        for factor in (1e-9, 1e6):
            with self.subTest(factor=factor):
                self.assert_set((factor, 2 * factor, 0.25 * factor**2, 0, 0, 2),
                                "bounded", [[0, 1]])

    def test_invalid_covariance_is_rejected(self):
        with self.assertRaises(ValueError):
            VERIFIER.fieller_set(1, 2, 1, 1, 2, 1)
        with self.assertRaises(ValueError):
            VERIFIER.fieller_set(1, 2, -1, 1, 0, 1)
        with self.assertRaises(ValueError):
            VERIFIER.fieller_set(1, 2, 1, 1, 0, float("nan"))


class SavedSummaryTests(unittest.TestCase):
    def test_independent_fictional_reference_passes(self):
        report = VERIFIER.verify_summary(fictional_summary())
        self.assertEqual(report["status"], "PASS", report["mismatches"])
        self.assertFalse(report["survey_covariance_reconstruction"])
        self.assertFalse(report["clean_environment_project_acceptance"])

    def test_route_order_is_used_for_covariance(self):
        payload = fictional_summary()
        permutation = [4, 2, 0, 3, 1]
        for domain in payload.values():
            order = domain["route_order"]
            domain["route_order"] = [order[i] for i in permutation]
            matrix = np.asarray(domain["joint_covariance_of_route_losses"])
            domain["joint_covariance_of_route_losses"] = matrix[np.ix_(permutation, permutation)].tolist()
        self.assertEqual(VERIFIER.verify_summary(payload)["status"], "PASS")

    def test_wrong_route_order_without_matrix_permutation_fails(self):
        payload = fictional_summary()
        payload["primary_40plus"]["route_order"] = ["P", "S", "B", "MEAN", "M"]
        self.assertEqual(VERIFIER.verify_summary(payload)["status"], "FAIL")

    def test_corrupted_contrast_and_retention_fail(self):
        payload = fictional_summary()
        payload["primary_40plus"]["contrasts"]["D_substitution_loss"]["estimate"] += 0.001
        payload["primary_40plus"]["retention"]["point"] = 1.0
        errors = VERIFIER.verify_summary(payload)["mismatches"]
        self.assertIn("primary_40plus.contrasts.D_substitution_loss.estimate", errors)
        self.assertIn("primary_40plus.retention.point", errors)

    def test_covariance_corruption_and_dimensions_fail(self):
        for change, expected_suffix in (
            (lambda matrix: matrix.__setitem__((0, 1), 0.00004), ".symmetric"),
            (lambda matrix: matrix.__setitem__(([0, 1], [1, 0]), 0.00004), ".positive_semidefinite"),
            (lambda matrix: matrix.__setitem__((0, 0), float("nan")), ".finite"),
        ):
            with self.subTest(kind=expected_suffix):
                payload = fictional_summary()
                matrix = np.array(payload["primary_40plus"]["joint_covariance_of_route_losses"])
                change(matrix)
                payload["primary_40plus"]["joint_covariance_of_route_losses"] = matrix.tolist()
                errors = VERIFIER.verify_summary(payload)["mismatches"]
                self.assertIn("primary_40plus.joint_covariance_of_route_losses" + expected_suffix, errors)
        payload = fictional_summary()
        payload["primary_40plus"]["joint_covariance_of_route_losses"] = [[1, 0], [0, 1]]
        self.assertEqual(VERIFIER.verify_summary(payload)["status"], "FAIL")

    def test_valid_but_wrong_covariance_and_ci_fail(self):
        payload = fictional_summary()
        payload["primary_40plus"]["joint_covariance_of_route_losses"][0][0] *= 2
        payload["primary_40plus"]["contrasts"]["G_measured_gain"]["lower"] += 0.01
        errors = VERIFIER.verify_summary(payload)["mismatches"]
        self.assertIn("primary_40plus.Brier.B.SE", errors)
        self.assertIn("primary_40plus.contrasts.G_measured_gain.lower", errors)

    def test_unweighted_identity_corruption_fails(self):
        payload = fictional_summary()
        payload["primary_40plus"]["unweighted_sensitivity"]["contrasts"]["A_proxy_over_mean"] = -0.02
        errors = VERIFIER.verify_summary(payload)["mismatches"]
        self.assertIn("primary_40plus.unweighted_sensitivity.contrasts.A_proxy_over_mean", errors)

    def test_cli_sanitizes_input_paths_and_untrusted_metadata(self):
        with tempfile.TemporaryDirectory(prefix="private-location-") as temporary:
            root = Path(temporary)
            source, output = root / "input.json", root / "safe-report.json"
            payload = fictional_summary()
            payload["protocol_id"] = str(root / "not-for-publication")
            source.write_text(json.dumps(payload), encoding="utf-8")
            result = subprocess.run([sys.executable, str(MODULE_PATH), "--input", str(source),
                                     "--output", str(output)], capture_output=True, text=True)
            self.assertEqual(result.returncode, 0)
            rendered = result.stdout + result.stderr + output.read_text(encoding="utf-8")
            self.assertNotIn(str(root), rendered)
            self.assertNotIn("not-for-publication", rendered)
            self.assertEqual(json.loads(result.stdout)["status"], "PASS")
            # An input error must also avoid echoing the exception or path.
            source.unlink()
            result = subprocess.run([sys.executable, str(MODULE_PATH), "--input", str(source),
                                     "--output", str(output)], capture_output=True, text=True)
            self.assertEqual(result.returncode, 2)
            self.assertNotIn(str(root), result.stdout + result.stderr)
            self.assertEqual(json.loads(result.stdout)["error"], "input_unreadable_or_invalid")
            # A failed run must replace its old PASS report, not leave stale success.
            self.assertEqual(json.loads(output.read_text(encoding="utf-8"))["status"], "ERROR")


if __name__ == "__main__":
    unittest.main()
